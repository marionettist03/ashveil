// ---------------------------------------------------------------- build everything
export const ART = { heroes: {}, enemies: {}, weapons: {}, props: {}, icons: {}, maud: null, ansel: null };

export function buildArt() {
  for (const id in HERO_ART) {
    const d = HERO_ART[id], A = HERO_ANIM[id];
    if (A) {
      // hand-made frames: idle, walk, atk, atkB, dash, hurt
      const set = { hand: d.hand, anim: true, w: A.w, h: A.h };
      for (const [name, list] of Object.entries(A.frames)) set[name] = list.map((layers) => makeSprite(composeRows(A.parts, layers, A.w, A.h, A.ox), A.pal));
      ART.heroes[id] = set;
    } else ART.heroes[id] = { ...buildFrames(d.rows, d.pal, d), hand: d.hand };
  }
  for (const id in ENEMY_ART) {
    const d = ENEMY_ART[id];
    ART.enemies[id] = buildFrames(d.rows, d.pal, d);
  }
  for (const id in WEAPONS) ART.weapons[id] = makeSprite(WEAPONS[id].rows, WEAPONS[id].pal);
  for (const id in PROP_ART) ART.props[id] = makeSprite(PROP_ART[id].rows, PROP_ART[id].pal);
  for (const id in ICON_ART) ART.icons[id] = makeSprite(ICON_ART[id].rows, ICON_ART[id].pal);
  ART.maud = buildFrames(MAUD.rows, MAUD.pal, { legTop: 25, split: 12, mode: 'legs' });
  ART.ansel = buildFrames(ANSEL.rows, ANSEL.pal, { legTop: 24, split: 12, mode: 'sway' });
}
