// Regenerates sw.js with a precache list of every game file and a content hash.
// Run after changing any file:  node tools/gen-sw.mjs
import { readdirSync, readFileSync, writeFileSync, statSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { join } from 'node:path';

const root = new URL('..', import.meta.url).pathname;
const files = ['index.html', 'style.css', 'manifest.webmanifest'];
const walk = (dir) => {
  for (const f of readdirSync(join(root, dir))) {
    const rel = join(dir, f);
    if (statSync(join(root, rel)).isDirectory()) walk(rel);
    else files.push(rel);
  }
};
walk('src');
walk('icons');
const h = createHash('sha1');
for (const f of files) h.update(f).update(readFileSync(join(root, f)));
const version = h.digest('hex').slice(0, 10);
const list = ['./', ...files.map((f) => './' + f.replace(/\\/g, '/'))];
writeFileSync(join(root, 'sw.js'), `// Offline cache for Ashveil (generated by tools/gen-sw.mjs; do not edit by hand).
const CACHE = 'ashveil-${version}';
const FILES = ${JSON.stringify(list, null, 2)};

self.addEventListener('install', (e) => {
  e.waitUntil(caches.open(CACHE).then((c) => c.addAll(FILES)).then(() => self.skipWaiting()));
});

self.addEventListener('activate', (e) => {
  e.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys.filter((k) => k !== CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim())
  );
});

self.addEventListener('fetch', (e) => {
  if (e.request.method !== 'GET') return;
  const url = new URL(e.request.url);
  if (url.origin !== location.origin) return;
  e.respondWith(
    caches.match(e.request, { ignoreSearch: true }).then((hit) => hit || fetch(e.request).then((res) => {
      if (res.ok) { const copy = res.clone(); caches.open(CACHE).then((c) => c.put(e.request, copy)); }
      return res;
    }).catch(() => caches.match('./index.html')))
  );
});
`);
console.log('sw.js written:', version, list.length, 'files');
